// 已查找过的字符缓存
const cache = new Map()

/**
 * 获取单个中文字符的拼音首字母
 * @param {string} char 单个字符
 * @returns {string} 拼音首字母，非中文则返回原字符
 */
function getCharInitial(char) {
  if (cache.has(char)) return cache.get(char)
  // 中文范围判断
  if (/[一-鿿]/.test(char)) {
    const result = CHAR_MAP[char] || char
    cache.set(char, result)
    return result
  }
  cache.set(char, char.toLowerCase())
  return char.toLowerCase()
}

